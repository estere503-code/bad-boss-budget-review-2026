assert.equal(p1.revenue[10], 16800);
assert.equal(p1.totals.revenue, 146650);
assert.equal(p2.revenue[5], 22750);
assert.equal(p2.totals.revenue, 216650);
assert.equal(validateDecision(strategyDecisions[0]).valid, true);
console.log("Domain tests passed.");
